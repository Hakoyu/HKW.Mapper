using System.CodeDom.Compiler;
using System.Text;
using HKW.SourceGeneratorUtils;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace HKW.Mapper.SourceGenerator;

internal class ClassSourceWriter
{
    public static void Execute(ClassInfo classInfo)
    {
        var w = new ClassSourceWriter(classInfo);
        w.Write();
    }

    private readonly ClassInfo _classInfo;
    private readonly IndentedTextWriter _writer;

    public ClassSourceWriter(ClassInfo classInfo)
    {
        _classInfo = classInfo;
        var stringStream = new StringWriter();
        _writer = new IndentedTextWriter(stringStream);
    }

    private void Write()
    {
        _writer.WriteLine("// <auto-generated>");
        _writer.WriteLine("#nullable enable");
        //_writer.WriteLine("#pragma warning disable CS1591");
        // 添加全部引用
        //_writer.WriteLine(_classInfo.Usings);
        // 添加命名空间
        var outputNamespace = _classInfo.UsesExternalContainer
            ? _classInfo.OutputContainerSymbol!.ContainingNamespace.ToDisplayString()
            : "HKW.Mapper";
        var hasNamespace = string.IsNullOrEmpty(outputNamespace) is false;
        if (hasNamespace)
        {
            _writer.WriteLine($"namespace {outputNamespace}");
            _writer.WriteLine("{");
            _writer.Indent++;
        }
        // 获取可访问性
        var declarationSyntax = _classInfo.OutputContainerSyntax ?? _classInfo.ClassSyntax!;
        var accessibility = declarationSyntax.Modifiers.GetAccessibility();
        var className = _classInfo.UsesExternalContainer
            ? _classInfo.OutputContainerSymbol!.Name
            : $"{_classInfo.ClassSymbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat).Replace('.', '_')}MapExtensions";
        _writer.WriteLine(
            $"{accessibility} static {(_classInfo.UsesExternalContainer ? "partial " : string.Empty)}class {className}"
        );
        _writer.WriteLine("{");
        _writer.Indent++;

        foreach (var converter in _classInfo.MapConverters)
            _writer.WriteInfo(converter);
        foreach (var config in _classInfo.MapConfigs)
            _writer.WriteInfo(config);
        foreach (var mapTarget in _classInfo.MapTargets)
        {
            if (mapTarget.Direction.HasFlag(MapDirections.To))
            {
                _writer.WriteInfo(mapTarget.MapToMethod);
                foreach (var method in mapTarget.MapToCreationMethods)
                    _writer.WriteInfo(method);
            }
            if (mapTarget.Direction.HasFlag(MapDirections.From))
                _writer.WriteInfo(mapTarget.MapFromMethod);
        }

        _writer.Indent--;
        _writer.WriteLine();
        _writer.WriteLine("}");
        if (hasNamespace)
        {
            _writer.Indent--;
            _writer.WriteLine("}");
        }
        var hintName = _classInfo.UsesExternalContainer
            ? $"{_classInfo.OutputContainerSymbol!.GetFullName()}_{_classInfo.ClassSymbol.GetFullName()}MapExtensions.g.cs"
            : $"{_classInfo.FullTypeName}MapExtensions.g.cs";
        _classInfo.ProductionContext.AddSource(
            hintName.ReplaceBraces().Replace('<', '_').Replace('>', '_'),
            ((StringWriter)_writer.InnerWriter).ToString()
        );
    }
}
